// Look up a translation. Falls back to English if the key is missing in the
// active language, then to the key itself so it's obvious in dev.
export function lookup(lang, key, vars) {
  const str = translations[lang]?.[key] ?? translations.en[key] ?? key
  if (!vars) return str
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`))
}